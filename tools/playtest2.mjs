// Test des écrans d'accueil après une course, du garage et du coffre.
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path'; import { chromium } from 'playwright-core';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, 'tools', 'playtest-out'); fs.mkdirSync(out, { recursive: true });
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.jpg': 'image/jpeg' };
const server = http.createServer((req, res) => { const p = path.join(root, decodeURIComponent(req.url.split('?')[0])); fs.readFile(p, (e, d) => { if (e) { res.writeHead(404); res.end(); return; } res.writeHead(200, { 'Content-Type': types[path.extname(p)] || 'application/octet-stream' }); res.end(d); }); }).listen(8767);
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
await page.route('https://cdn.jsdelivr.net/npm/three@0.186.1/**', (route) => route.fulfill({ path: path.join(root, 'node_modules/three', route.request().url().split('three@0.186.1/')[1]), contentType: 'text/javascript' }));
await page.route('https://fonts.googleapis.com/**', r => r.abort());
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.goto('http://localhost:8767/index.html');
await page.waitForFunction(() => window.__hk);
await page.evaluate(() => { const e = window.__hk.eco; e.s.yellow = 900; e.s.blue = 6000; e.s.gems = 3; e.s.chestAt = Date.now() - 1; e.save(); });
await page.waitForTimeout(1500);
await page.screenshot({ path: path.join(out, '7-accueil-argent.png') });
await page.click('#b-chest', { force: true }); await page.waitForTimeout(500);
await page.screenshot({ path: path.join(out, '8-coffre.png') });
await page.click('#b-chestok'); await page.click('.card button', { force: true }); await page.click('#b-booster', { force: true });
await page.waitForTimeout(800);
await page.screenshot({ path: path.join(out, '9-apres-achats.png') });
await page.click('#b-garage', { force: true }); await page.waitForTimeout(500);
await page.click('.g-card:nth-child(5)', { force: true }); await page.waitForTimeout(300);
await page.screenshot({ path: path.join(out, '10-garage.png') });
await page.click('#b-gact'); await page.click('#b-garageclose'); await page.waitForTimeout(1200);
await page.screenshot({ path: path.join(out, '11-taxi.png') });
console.log(JSON.stringify(await page.evaluate(() => window.__hk.eco.s)));
console.log('erreurs:', errors.length ? errors.join('\n') : 'aucune');
await browser.close(); server.close();
